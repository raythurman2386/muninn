#!/usr/bin/env bash
# Point the workspace at a local Rune checkout instead of the pinned git revision.
#
#   ./scripts/use-local-rune.sh                 # ../rune-fun
#   RUNE_DIR=/path/to/rune ./scripts/use-local-rune.sh
#
# Revert with: rm .cargo/config.toml
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
rune_dir="${RUNE_DIR:-$root/../rune-fun}"
rune_dir="$(cd "$rune_dir" && pwd)"

for path in \
  "$rune_dir/crates/rune" \
  "$rune_dir/crates/rune-kit" \
  "$rune_dir/themes/opencode"
do
  if [[ ! -d "$path" ]]; then
    echo "not a Rune checkout: $path" >&2
    exit 1
  fi
done

mkdir -p "$root/.cargo"
cat > "$root/.cargo/config.toml" <<EOF
# Generated by scripts/use-local-rune.sh. Do not commit.
[patch."https://github.com/anomalyco/rune.git"]
rune = { path = "$rune_dir/crates/rune" }
rune-kit = { path = "$rune_dir/crates/rune-kit" }
rune-theme-opencode = { path = "$rune_dir/themes/opencode" }
EOF

echo "using local Rune from $rune_dir"
echo "revert with: rm $root/.cargo/config.toml"
