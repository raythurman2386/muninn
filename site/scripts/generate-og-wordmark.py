#!/usr/bin/env python3
"""Regenerate scripts/og-wordmark.svg from Inter (text converted to paths).

Used only when the OG wordmark copy changes. The usual icon pipeline
(scripts/generate-icons.mjs) rasterizes the committed SVG and does not need
a font. Requires fontTools and a variable Inter TTF (set INTER_TTF, or pass
the path as the first argument).
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

from fontTools.misc.transform import Transform
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

SITE = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent / "og-wordmark.svg"
DEFAULTS = [
    os.environ.get("INTER_TTF"),
    "/usr/share/fonts/truetype/sand-box/google/Inter/Inter-VariableFont_opsz,wght.ttf",
    "/usr/share/fonts/truetype/inter/Inter-VariableFont_opsz,wght.ttf",
]


def find_font() -> Path:
    args = [sys.argv[1]] if len(sys.argv) > 1 else []
    for raw in args + DEFAULTS:
        if raw and Path(raw).is_file():
            return Path(raw)
    raise SystemExit(
        "Inter variable TTF not found. Pass the path or set INTER_TTF."
    )


def instantiate(font_path: Path, wght: float, opsz: float) -> TTFont:
    return instantiateVariableFont(TTFont(font_path), {"wght": wght, "opsz": opsz}, overlap=True)


def text_paths(font: TTFont, text: str, font_size: float, fill: str) -> tuple[str, float]:
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = font_size / font["head"].unitsPerEm
    x = 0.0
    parts: list[str] = []
    for ch in text:
        name = cmap[ord(ch)]
        glyph = glyph_set[name]
        pen = SVGPathPen(glyph_set)
        glyph.draw(TransformPen(pen, Transform(scale, 0, 0, -scale, x, 0)))
        d = pen.getCommands()
        if d:
            parts.append(f'    <path fill="{fill}" d="{d}"/>')
        x += glyph.width * scale
    return "\n".join(parts), x


def main() -> None:
    font_path = find_font()
    title, title_w = text_paths(instantiate(font_path, 640, 72), "Muninn", 72, "#fafafa")
    sub, sub_w = text_paths(
        instantiate(font_path, 500, 24),
        "A local-first Markdown vault with a knowledge graph.",
        24,
        "#aeaeae",
    )
    width = int(max(title_w, sub_w) + 6)
    height = 130
    OUT.write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- Wordmark for the default OG image. Text is Inter (OFL), converted to paths\n"
        "     so the generate-icons script can rasterize without a font installed.\n"
        "     Regenerated by site/scripts/generate-og-wordmark.py if the copy changes. -->\n"
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">\n'
        '  <g id="title" transform="translate(0, 72)">\n'
        f"{title}\n"
        "  </g>\n"
        '  <g id="sub" transform="translate(0, 116)">\n'
        f"{sub}\n"
        "  </g>\n"
        "</svg>\n"
    )
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes) title_w={title_w:.1f} sub_w={sub_w:.1f}")


if __name__ == "__main__":
    main()
