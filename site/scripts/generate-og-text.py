#!/usr/bin/env python3
"""Render Inter text to path SVGs for the W8 OG images.

Used only when the OG copy changes. `scripts/generate-og.mjs` rasterizes the
committed SVGs with sharp and does not need a font.

Requires fontTools and a variable Inter TTF. Pass the path as the first
argument, set INTER_TTF, or have fontconfig resolve the Inter family. There
is no hard-coded filesystem path.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

from fontTools.misc.transform import Transform
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

OUT_DIR = Path(__file__).resolve().parent / "og-text"

# Palette from site/src/styles/tokens.css (dark theme).
COLOR_TITLE = "#fafafa"
COLOR_MUTED = "#aeaeae"
COLOR_ACCENT = "#a2bcff"

# Vertical layout inside each text SVG, in px. The compositor vertically
# centres the whole block on the 630 px canvas.
HOME_TITLE_SIZE = 72
HOME_TITLE_Y = 72
HOME_SUB_SIZE = 24
HOME_SUB_Y = 116
HOME_HEIGHT = 130

EYEBROW_SIZE = 28
EYEBROW_Y = 28
PAGE_TITLE_SIZE = 72
PAGE_TITLE_Y = 112
PAGE_SUB_SIZE = 24
PAGE_SUB_Y = 156
PAGE_HEIGHT = 170


def find_font() -> Path:
    candidates: list[Path] = []
    if len(sys.argv) > 1:
        candidates.append(Path(sys.argv[1]))
    env = os.environ.get("INTER_TTF")
    if env:
        candidates.append(Path(env))
    for raw in candidates:
        if raw.is_file():
            return raw
        raise SystemExit(f"Inter TTF not found: {raw}")
    if shutil.which("fc-list"):
        try:
            out = subprocess.check_output(
                ["fc-list", ":family=Inter:style=Regular", "file"],
                text=True,
                stderr=subprocess.DEVNULL,
            )
        except subprocess.CalledProcessError:
            out = ""
        if not out.strip():
            try:
                out = subprocess.check_output(
                    ["fc-list", ":family=Inter", "file"],
                    text=True,
                    stderr=subprocess.DEVNULL,
                )
            except subprocess.CalledProcessError:
                out = ""
        files = [Path(line.split(":")[0].strip()) for line in out.splitlines() if line.strip()]
        preferred = [
            p for p in files if p.is_file() and "Variable" in p.name and p.suffix.lower() in {".ttf", ".otf"}
        ]
        regular = [p for p in files if p.is_file() and p.suffix.lower() in {".ttf", ".otf"}]
        if preferred:
            return preferred[0]
        if regular:
            return regular[0]
    raise SystemExit(
        "Inter variable TTF not found. Pass the path as the first argument or set INTER_TTF."
    )


def instantiate(font_path: Path, wght: float, opsz: float) -> TTFont:
    return instantiateVariableFont(TTFont(font_path), {"wght": wght, "opsz": opsz}, overlap=True)


def text_paths(font: TTFont, text: str, font_size: float, fill: str) -> tuple[str, float]:
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = font_size / font["head"].unitsPerEm
    x = 0.0
    parts: list[str] = []
    for ch in text:
        name = cmap.get(ord(ch))
        if name is None:
            raise SystemExit(f"Inter is missing a glyph for {ch!r} (U+{ord(ch):04X})")
        glyph = glyph_set[name]
        pen = SVGPathPen(glyph_set)
        glyph.draw(TransformPen(pen, Transform(scale, 0, 0, -scale, x, 0)))
        d = pen.getCommands()
        if d:
            parts.append(f'    <path fill="{fill}" d="{d}"/>')
        x += glyph.width * scale
    return "\n".join(parts), x


def write_svg(name: str, width: float, height: int, groups: str) -> None:
    width_i = int(width + 6)
    path = OUT_DIR / f"{name}.svg"
    path.write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- OG wordmark. Text is Inter (OFL), converted to paths so\n"
        "     generate-og.mjs can rasterize without a font installed.\n"
        "     Regenerated by site/scripts/generate-og-text.py if the copy changes. -->\n"
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width_i}" height="{height}" '
        f'viewBox="0 0 {width_i} {height}">\n'
        f"{groups}"
        "</svg>\n"
    )
    print(f"wrote {path} ({path.stat().st_size} bytes, {width_i}x{height})")


def main() -> None:
    font_path = find_font()
    title_font = instantiate(font_path, 640, 72)
    eyebrow_font = instantiate(font_path, 600, 28)
    sub_font = instantiate(font_path, 500, 24)
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    # Home matches the W3 default card: large "Muninn" plus the tagline, no eyebrow.
    title, title_w = text_paths(title_font, "Muninn", HOME_TITLE_SIZE, COLOR_TITLE)
    sub, sub_w = text_paths(
        sub_font,
        "A local-first Markdown vault with a knowledge graph.",
        HOME_SUB_SIZE,
        COLOR_MUTED,
    )
    write_svg(
        "home",
        max(title_w, sub_w),
        HOME_HEIGHT,
        '  <g id="title" transform="translate(0, '
        + str(HOME_TITLE_Y)
        + ')">\n'
        + title
        + "\n  </g>\n"
        + '  <g id="sub" transform="translate(0, '
        + str(HOME_SUB_Y)
        + ')">\n'
        + sub
        + "\n  </g>\n",
    )

    pages = [
        ("features", "Features", "Notes, Board, Kanban, and the knowledge graph."),
        ("download", "Download", "Linux, macOS, and Windows builds."),
        ("docs", "Docs", "Getting started and user guides."),
        ("changelog", "Changelog", "Release notes for every version."),
        ("privacy", "Privacy", "How Muninn handles your data."),
        ("sponsor", "Sponsor", "Support Muninn's development."),
        ("press", "Press", "Logos, screenshots, and product facts."),
    ]
    for slug, heading, line in pages:
        eyebrow, eyebrow_w = text_paths(eyebrow_font, "Muninn", EYEBROW_SIZE, COLOR_ACCENT)
        heading_paths, heading_w = text_paths(title_font, heading, PAGE_TITLE_SIZE, COLOR_TITLE)
        line_paths, line_w = text_paths(sub_font, line, PAGE_SUB_SIZE, COLOR_MUTED)
        write_svg(
            slug,
            max(eyebrow_w, heading_w, line_w),
            PAGE_HEIGHT,
            '  <g id="eyebrow" transform="translate(0, '
            + str(EYEBROW_Y)
            + ')">\n'
            + eyebrow
            + "\n  </g>\n"
            + '  <g id="title" transform="translate(0, '
            + str(PAGE_TITLE_Y)
            + ')">\n'
            + heading_paths
            + "\n  </g>\n"
            + '  <g id="sub" transform="translate(0, '
            + str(PAGE_SUB_Y)
            + ')">\n'
            + line_paths
            + "\n  </g>\n",
        )


if __name__ == "__main__":
    main()
